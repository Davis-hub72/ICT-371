-- ---- Task 2: IF ELSIF ELSE on seat availability ----
DO $$
DECLARE
    v_seats integer;
BEGIN
    SELECT available_seats INTO v_seats
    FROM events WHERE event_id = 2;

    IF v_seats = 0 THEN
        RAISE NOTICE 'Event full';
    ELSIF v_seats <= 2 THEN
        RAISE NOTICE 'Event nearly full: % seats left', v_seats;
    ELSE
        RAISE NOTICE 'Event has plenty of seats: % left', v_seats;
    END IF;
END;
$$ LANGUAGE plpgsql;
-- Expected message: "Event nearly full: 2 seats left"

-- ---- Task 3: WHILE loop (booking reminders) and FOR loop (entrance checks) ----
DO $$
DECLARE
    v_day integer := 1;
BEGIN
    WHILE v_day <= 3 LOOP
        RAISE NOTICE 'Booking reminder day %', v_day;
        v_day := v_day + 1;
