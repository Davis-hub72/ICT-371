$$ LANGUAGE plpgsql;
-- Expected: 3 booking-reminder notices, then 3 entrance-check notices

-- ---- Task 4: book_seats procedure ----
CREATE OR REPLACE PROCEDURE book_seats(
    p_event_id       integer,
    p_student_number text,
    p_seats          integer
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_available  integer;
    v_booking_id integer;
BEGIN
    IF p_seats <= 0 THEN
        RAISE EXCEPTION 'Seat count must be positive'
            USING ERRCODE = '22023';
    END IF;

    SELECT available_seats INTO v_available
    FROM events
    WHERE event_id = p_event_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'Event % does not exist', p_event_id;
        RETURN;
    ELSIF v_available < p_seats THEN
        RAISE NOTICE 'Insufficient seats: only % remaining', v_available;
        RETURN;
    END IF;

    UPDATE events
    SET available_seats = available_seats - p_seats
    WHERE event_id = p_event_id;

    INSERT INTO bookings (event_id, student_number, seats, status)
    VALUES (p_event_id, p_student_number, p_seats, 'ACTIVE')
    RETURNING booking_id INTO v_booking_id;

    RAISE NOTICE 'Booking % created for student %', v_booking_id, p_student_number;
END;
$$;

