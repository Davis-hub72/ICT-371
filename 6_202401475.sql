-- ---- Task 6: cancel_booking procedure (idempotent on repeat call) ----
CREATE OR REPLACE PROCEDURE cancel_booking(p_booking_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_event_id integer;
    v_seats    integer;
BEGIN
    SELECT event_id, seats
    INTO v_event_id, v_seats
    FROM bookings
    WHERE booking_id = p_booking_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active booking with ID %', p_booking_id;
        RETURN;
    END IF;

    UPDATE bookings
    SET status = 'CANCELLED'
    WHERE booking_id = p_booking_id;

    UPDATE events
    SET available_seats = available_seats + v_seats
    WHERE event_id = v_event_id;

    RAISE NOTICE 'Booking % cancelled; % seats released', p_booking_id, v_seats;
END;
$$;

CALL cancel_booking(1);
CALL cancel_booking(1);   -- second call: already CANCELLED, must not release seats again
-- Expected: first call releases seats and prints confirmation;
--           second call prints "No active booking with ID 1"

-- ---- Task 7: Explicit cursor for full or nearly full events ----
CREATE OR REPLACE PROCEDURE show_full_or_near_full_events()
LANGUAGE plpgsql
AS $$
DECLARE
    v_event  record;
    c_full   CURSOR FOR
        SELECT event_name, available_seats
        FROM events
        WHERE available_seats <= 2
        ORDER BY event_id;
BEGIN
    OPEN c_full;
    LOOP
        FETCH c_full INTO v_event;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Full or nearly full: % (% remaining)', v_event.event_name, v_event.available_seats;
    END LOOP;
    CLOSE c_full;
END;
$$;

CALL show_full_or_near_full_events();
-- Expected: at least "Guest Lecture: AI in Africa (2 remaining)" is reported

