-- ---- Task 6: return_tool procedure (idempotent on repeat call) ----
CREATE OR REPLACE PROCEDURE return_tool(p_loan_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_tool_id  integer;
    v_quantity integer;
BEGIN
    SELECT tool_id, quantity
    INTO v_tool_id, v_quantity
    FROM tool_loans
    WHERE loan_id = p_loan_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active loan with ID %', p_loan_id;
        RETURN;
    END IF;

    UPDATE tool_loans
    SET status = 'RETURNED'
    WHERE loan_id = p_loan_id;

    UPDATE tools
    SET available_quantity = available_quantity + v_quantity
    WHERE tool_id = v_tool_id;

    RAISE NOTICE 'Loan % returned; % units restored to stock', p_loan_id, v_quantity;
END;
$$;

CALL return_tool(1);
CALL return_tool(1);   -- second call: already RETURNED, must not add stock again
-- Expected: first call restores stock and prints confirmation;
--           second call prints "No active loan with ID 1"

-- ---- Task 7: Explicit cursor for tools with low availability ----
CREATE OR REPLACE PROCEDURE show_low_availability_tools()
LANGUAGE plpgsql
AS $$
DECLARE
    v_tool  record;
    c_low   CURSOR FOR
        SELECT tool_name, available_quantity
        FROM tools
        WHERE available_quantity <= 2
        ORDER BY tool_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_tool;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low availability: % (% remaining)', v_tool.tool_name, v_tool.available_quantity;
    END LOOP;
    CLOSE c_low;
END;
$$;

CALL show_low_availability_tools();
-- Expected: at least "Soldering Iron (2 remaining)" is reported

