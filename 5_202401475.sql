-- ---- Task 2: IF ELSIF ELSE on tool availability ----
DO $$
DECLARE
    v_quantity integer;
BEGIN
    SELECT available_quantity INTO v_quantity
    FROM tools WHERE tool_id = 2;

    IF v_quantity = 0 THEN
        RAISE NOTICE 'Tool unavailable';
    ELSIF v_quantity <= 2 THEN
        RAISE NOTICE 'Tool low on stock: % remaining', v_quantity;
    ELSE
        RAISE NOTICE 'Tool readily available: % remaining', v_quantity;
    END IF;
END;
$$ LANGUAGE plpgsql;
-- Expected message: "Tool low on stock: 2 remaining"

